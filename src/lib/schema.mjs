// The whole database, in one string, shared by the app (src/lib/db.ts) and the
// setup/seed scripts so there is only ever one definition of the schema.
//
// PostgreSQL. The portal ran on SQLite until 27 Nov 2026; `schema.sqlite.mjs`
// keeps that definition for the one-time data migration and nothing else.
//
// Two things deliberately kept from the SQLite shape, because changing them
// would have meant touching every page that reads a row:
//   - Timestamps stay TEXT in 'YYYY-MM-DD HH:MM:SS' UTC, the exact format
//     SQLite's datetime('now') produced, so every formatter still works.
//   - Flags stay INTEGER 0/1 rather than BOOLEAN, so `must_reset === 1` and
//     friends still mean what they meant.
//
// One thing deliberately changed: the throttle windows hold Date.now(), which
// is about 1.7e12 and overflows a Postgres INTEGER (max 2.1e9). SQLite's
// INTEGER is 64-bit and hid this. They are BIGINT here.
const NOW = "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')";

export const SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'client',
    session_version INTEGER NOT NULL DEFAULT 0,
    must_reset INTEGER NOT NULL DEFAULT 1,
    seen_intro INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active',
    project_name TEXT NOT NULL DEFAULT '',
    starts_on TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT ${NOW},
    last_seen_at TEXT
  );

  CREATE TABLE IF NOT EXISTS progress (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    step_id TEXT NOT NULL,
    completed_at TEXT NOT NULL DEFAULT ${NOW},
    PRIMARY KEY (user_id, step_id)
  );

  CREATE TABLE IF NOT EXISTS form_responses (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    form_id TEXT NOT NULL,
    data TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'draft',
    updated_at TEXT NOT NULL DEFAULT ${NOW},
    submitted_at TEXT,
    PRIMARY KEY (user_id, form_id)
  );

  CREATE TABLE IF NOT EXISTS deliverables (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    kind TEXT NOT NULL DEFAULT 'other',
    status TEXT NOT NULL DEFAULT 'queued',
    url TEXT NOT NULL DEFAULT '',
    due_on TEXT NOT NULL DEFAULT '',
    position INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${NOW},
    delivered_at TEXT,
    approved_at TEXT
  );

  CREATE TABLE IF NOT EXISTS files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    uploaded_by INTEGER NOT NULL,
    uploader_role TEXT NOT NULL DEFAULT 'client',
    label TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT 'general',
    file_name TEXT NOT NULL,
    stored_name TEXT NOT NULL,
    mime TEXT NOT NULL DEFAULT '',
    size BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_id INTEGER NOT NULL,
    author_role TEXT NOT NULL DEFAULT 'client',
    author_name TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT ${NOW},
    read_by_client INTEGER NOT NULL DEFAULT 0,
    read_by_admin INTEGER NOT NULL DEFAULT 0
  );

  CREATE TABLE IF NOT EXISTS notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS activity (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    actor_name TEXT NOT NULL DEFAULT '',
    actor_role TEXT NOT NULL DEFAULT 'client',
    kind TEXT NOT NULL,
    summary TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL DEFAULT ''
  );

  CREATE TABLE IF NOT EXISTS auth_login_attempts (
    bucket_hash TEXT PRIMARY KEY,
    failures INTEGER NOT NULL DEFAULT 0,
    window_started_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS rate_limits (
    bucket_hash TEXT PRIMARY KEY,
    hits INTEGER NOT NULL DEFAULT 0,
    window_started_at BIGINT NOT NULL
  );

  CREATE INDEX IF NOT EXISTS idx_deliverables_user ON deliverables(user_id);
  CREATE INDEX IF NOT EXISTS idx_files_user ON files(user_id);
  CREATE INDEX IF NOT EXISTS idx_messages_user ON messages(user_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_activity_created ON activity(created_at);
`;
